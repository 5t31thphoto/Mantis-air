"""The aircraft models into the game: one generated header per aircraft (src/art_mesh_<name>.h), read by art_mesh.h.

A model's faces are textured from the same views the cards are made from (cards.load_views), so its UVs are moved from
a view's pixels to its card's texels (mip 0): the cards' texture data is reused as it is, nothing new is stored but
the geometry.
"""
import numpy as np, cards

def card_dims(views):
    """Each view's card size (mip 0), as cards.py makes them."""
    ta, tm, _ = views['top']; sa, sm, _ = views['side']; fa, fm, _ = views['front' if 'front' in views else 'rear']
    S = 1.0; L = tm.shape[0] / tm.shape[1]
    h_side = L * sm.shape[0] / sm.shape[1]; h_front = fm.shape[0] / fm.shape[1]
    Hn = float(np.sqrt(h_side * h_front))
    dims = {'top': (S, L), 'side': (L, Hn), 'front': (S, Hn), 'rear': (S, Hn)}
    big = max(S, L)
    out = {}
    for k in views:
        cw, ch = dims[k]
        out[k] = (max(4, int(round(cards.CARD_MAX * cw / big))), max(4, int(round(cards.CARD_MAX * ch / big))))
    return out

def livery_index(rgb, header='src/art_cards.h', name='LIVERY16_MANTIS'):
    """The nearest colour of a livery (as generated into art_cards.h) to rgb: 1..15."""
    txt = open(header).read()
    i = txt.index(name + '[16][3] = {'); j = txt.index('};', i)
    import re
    cols = np.array([[int(a), int(b), int(c)] for a, b, c in re.findall(r'\{(\d+), (\d+), (\d+)\}', txt[i:j + 2])][:16])
    d = ((cols[1:] - np.asarray(rgb)[None, :]) ** 2).sum(1)
    return int(np.argmin(d)) + 1

_NEAR = {}
def fill_index(img, mask, uv, key):
    """A textured face's stand-in colour, for any of its texels the view leaves empty (a part the view hides or
    draws thinner than the model has it): the view's paint under the face, or the nearest paint to it."""
    from scipy import ndimage
    if key not in _NEAR: _NEAR[key] = ndimage.distance_transform_edt(~mask, return_distances=False, return_indices=True)
    iy, ix = _NEAR[key]
    H, W = mask.shape
    cols = []
    for w in ((1/3, 1/3, 1/3), (0.6, 0.2, 0.2), (0.2, 0.6, 0.2), (0.2, 0.2, 0.6)):
        x, y = (np.asarray(w)[:, None] * uv).sum(0)
        x = int(np.clip(x, 0, W - 1)); y = int(np.clip(y, 0, H - 1))
        cols.append(img[iy[y, x], ix[y, x]])
    return livery_index(np.mean(cols, 0))

VIEW_ID = {'top': 0, 'side': 1, 'front': 2, 'rear': 3}

def write(path, tag, verts, tris, span, gear_h, props):
    """verts: model frame metres (forward, up, right; origin where the game's pose is: gear_h above the wheels).
    tris: (i0, i1, i2, view or None, uv 3x2 in card texels or None, livery index for a solid face or 0).
    props: [(forward, up, right, radius)] metres."""
    V = np.asarray(verts, float)
    L = [f'// Generated by tools/art ({tag.lower()} model). Do not edit.', '#pragma once', '#include "art_mesh.h"',
         'namespace mantis {', f'static const float MESH_{tag}_V[{len(V) * 3}] = {{']
    flat = [f'{x:.3f}f' for p in V for x in p]
    for k in range(0, len(flat), 12): L.append('    ' + ', '.join(flat[k:k + 12]) + ',')
    L.append('};')
    L.append(f'static const MeshTri MESH_{tag}_T[{len(tris)}] = {{')
    for t in tris:
        (i0, i1, i2, view, uv, col), g = t[:6], (t[6] if len(t) > 6 else 0)   # g: 0x80 a retracting gear's face
        n = np.cross(V[i1] - V[i0], V[i2] - V[i0]); n = n / (np.linalg.norm(n) + 1e-12)
        nq = [int(round(x * 127)) for x in n]
        if view is None:
            vid, uvq = 4 | g, [[0, 0]] * 3
        else:
            vid = VIEW_ID[view] | g; uvq = [[int(round(float(uv[c][0]) * 16)), int(round(float(uv[c][1]) * 16))] for c in range(3)]
        L.append(f'    {{{{{i0}, {i1}, {i2}}}, {vid}, {col}, {{{{{uvq[0][0]}, {uvq[0][1]}}}, {{{uvq[1][0]}, {uvq[1][1]}}}, {{{uvq[2][0]}, {uvq[2][1]}}}}}, {{{nq[0]}, {nq[1]}, {nq[2]}}}}},')
    L.append('};')
    pr = ', '.join('{' + ', '.join(f'{x:.3f}f' for x in p) + '}' for p in props) or '{0}'
    L.append(f'static const MeshArt MESH_{tag} = {{{len(V)}, {len(tris)}, MESH_{tag}_V, MESH_{tag}_T, {span:.3f}f, {gear_h:.3f}f, {len(props)}, {{{pr}}}}};')
    L.append('}')
    open(path, 'w').write('\n'.join(L) + '\n')
    return len(V), len(tris)
